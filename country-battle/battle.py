def flag_emoji(code):
    return "".join(chr(0x1F1E6 + ord(c) - ord("A")) for c in code.upper())


# --------------------------------------------------------------------------
# Simulation (deterministic for a given seed + country list)
# --------------------------------------------------------------------------
class Ball:
    def __init__(self, idx, code, x, y, vx, vy):
        self.idx, self.code = idx, code
        self.x, self.y, self.vx, self.vy = x, y, vx, vy
        self.hp = 100.0
        self.alive = True
        self.flash = 0.0


def arena_radius(t, alive, n):
    start = 470
    # shrink with time and with eliminations, never below 230
    frac = 1 - alive / n
    target = start - 170 * frac - 2.2 * max(0, t - 2)
    floor = 150 + 12 * alive  # final duel happens in a tight ring
    return max(min(230.0, floor), target)


def simulate(codes, seed, max_t=75.0):
    rng = random.Random(seed)
    n = len(codes)
    balls = []
    # spawn on a ring so nothing overlaps
    for i, c in enumerate(codes):
        a = 2 * math.pi * i / n + rng.uniform(-0.1, 0.1)
        rr = 330 if i % 2 == 0 else 200
        x, y = CX + rr * math.cos(a), CY + rr * math.sin(a)
        sa = rng.uniform(0, 2 * math.pi)
        sp = rng.uniform(450, 600)
        balls.append(Ball(i, c, x, y, sp * math.cos(sa), sp * math.sin(sa)))

    frames, events = [], []
    cooldown = {}
    sub = 4
    dt = 1 / FPS / sub
    R = 470.0
    t = 0.0
    f = 0
    winner = None
    order = []  # elimination order
    while t < max_t:
        alive = [b for b in balls if b.alive]
        R_target = arena_radius(t, len(alive), n)
        R += (R_target - R) * 0.02
        sudden = t > 30
        target_speed = 430 + (n - len(alive)) * 22 + (150 if sudden else 0)
        for _ in range(sub):
            for b in alive:
                b.x += b.vx * dt
                b.y += b.vy * dt
                dx, dy = b.x - CX, b.y - CY
                d = math.hypot(dx, dy)
                if d + BALL_R > R:
                    nx, ny = dx / d, dy / d
                    b.x, b.y = CX + nx * (R - BALL_R), CY + ny * (R - BALL_R)
                    vn = b.vx * nx + b.vy * ny
                    if vn > 0:
                        b.vx -= 2 * vn * nx
                        b.vy -= 2 * vn * ny
                        # tiny random deflection keeps paths from looping
                        ang = rng.uniform(-0.15, 0.15)
                        ca, sa_ = math.cos(ang), math.sin(ang)
                        b.vx, b.vy = b.vx * ca - b.vy * sa_, b.vx * sa_ + b.vy * ca
                        events.append((f, "wall", b.idx, None, 0))
            for i in range(len(alive)):
                a = alive[i]
                if not a.alive:
                    continue
                for j in range(i + 1, len(alive)):
                    if not a.alive:
                        break
                    b = alive[j]
                    if not b.alive:
                        continue
                    dx, dy = b.x - a.x, b.y - a.y
                    d = math.hypot(dx, dy)
                    if d >= 2 * BALL_R or d == 0:
                        continue
                    nx, ny = dx / d, dy / d
                    ov = 2 * BALL_R - d
                    a.x -= nx * ov / 2; a.y -= ny * ov / 2
                    b.x += nx * ov / 2; b.y += ny * ov / 2
                    va = a.vx * nx + a.vy * ny
                    vb = b.vx * nx + b.vy * ny
                    if va - vb <= 0:
                        continue
                    a.vx += (vb - va) * nx; a.vy += (vb - va) * ny
                    b.vx += (va - vb) * nx; b.vy += (va - vb) * ny
                    key = (min(a.idx, b.idx), max(a.idx, b.idx))
                    if cooldown.get(key, -1) > t:
                        continue
                    cooldown[key] = t + 0.25
                    # the ball pushing harder along the normal is more likely to win the hit
                    pa = max(va, 0.1) + 200
                    pb = max(-vb, 0.1) + 200
                    att, dfd = (a, b) if rng.random() < pa / (pa + pb) else (b, a)
                    dmg = rng.uniform(2, 12) * (1.8 if sudden else 1.0) * (1 + 0.05 * (n - len(alive)))
                    crit = rng.random() < 0.12
                    if crit:
                        dmg *= 2.6
                    dmg = round(dmg)
                    dfd.hp -= dmg
                    dfd.flash = 1.0
                    hx, hy = (a.x + b.x) / 2, (a.y + b.y) / 2
                    events.append((f, "crit" if crit else "hit", att.idx, dfd.idx, dmg, hx, hy))
                    if dfd.hp <= 0:
                        dfd.alive = False
                        dfd.hp = 0
                        order.append(dfd.idx)
                        events.append((f, "kill", att.idx, dfd.idx, 0, dfd.x, dfd.y))
                        heal = min(30, 100 - att.hp)
                        att.hp += heal
            alive = [b for b in balls if b.alive]
        # endgame: survivors hunt each other so the duel never stalls
        if 2 <= len(alive) <= 4:
            for b in alive:
                others = [o for o in alive if o is not b]
                tgt = min(others, key=lambda o: (o.x - b.x) ** 2 + (o.y - b.y) ** 2)
                dx, dy = tgt.x - b.x, tgt.y - b.y
                d = math.hypot(dx, dy) or 1
                b.vx += dx / d * 900 / FPS
                b.vy += dy / d * 900 / FPS
        # keep the energy up
        for b in alive:
            sp = math.hypot(b.vx, b.vy)
            k = (target_speed / sp) ** 0.08
            b.vx *= k; b.vy *= k
            b.flash = max(0, b.flash - 0.12)
        frames.append({
            "t": t, "R": R, "sudden": sudden,
            "balls": [(b.x, b.y, b.hp, b.alive, b.flash) for b in balls],
        })
        t += 1 / FPS
        f += 1
        if len(alive) <= 1:
            winner = alive[0].idx if alive else order[-1]
            break
    if winner is None:  # timeout: most HP wins
        winner = max((b for b in balls if b.alive), key=lambda b: b.hp).idx
        for b in sorted((b for b in balls if b.alive and b.idx != winner), key=lambda b: b.hp):
            order.append(b.idx)
    return frames, events, winner, order


