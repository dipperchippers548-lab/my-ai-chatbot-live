def text(c, s, x, y, size, rgb=(1, 1, 1), stroke=8, align="center", alpha=1.0, srgb=(0, 0, 0)):
    c.select_font_face(FONT, cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_BOLD)
    c.set_font_size(size)
    e = c.text_extents(s)
    if align == "center":
        tx = x - e.x_advance / 2
    elif align == "right":
        tx = x - e.x_advance
    else:
        tx = x
    c.move_to(tx, y)
    c.text_path(s)
    if stroke:
        c.set_source_rgba(*srgb, alpha)
        c.set_line_width(stroke)
        c.set_line_join(cairo.LINE_JOIN_ROUND)
        c.stroke_preserve()
    c.set_source_rgba(*rgb, alpha)
    c.fill()
    return e.x_advance


def hp_color(hp):
    if hp > 60:
        return (0.2, 0.95, 0.4)
    if hp > 30:
        return (1.0, 0.8, 0.1)
    return (1.0, 0.25, 0.25)


def ease_out_back(x):
    c1, c3 = 1.70158, 2.70158
    return 1 + c3 * (x - 1) ** 3 + c1 * (x - 1) ** 2


# --------------------------------------------------------------------------
# Audio synthesis
# --------------------------------------------------------------------------
def env(n, attack=0.002, decay=0.1):
    t = np.arange(n) / SR
    a = np.minimum(1, t / max(attack, 1e-4))
    return a * np.exp(-t / decay)


def tone(freq_start, freq_end, dur, decay, wave_="sine"):
    n = int(dur * SR)
    t = np.arange(n) / SR
    f = freq_start * (freq_end / freq_start) ** (t / dur)
    ph = 2 * np.pi * np.cumsum(f) / SR
    s = np.sin(ph) if wave_ == "sine" else np.sign(np.sin(ph)) * 0.5 + np.sin(ph) * 0.5
    return s * env(n, 0.002, decay)


def noise(dur, decay, rng, lowpass=0.0):
    n = int(dur * SR)
    s = rng.standard_normal(n)
    if lowpass:
        out = np.empty(n)
        acc = 0.0
        for i in range(n):
            acc += lowpass * (s[i] - acc)
            out[i] = acc
        s = out / (np.abs(out).max() + 1e-9)
    return s * env(n, 0.001, decay)


def mix(*parts):
    n = max(len(p) for p in parts)
    out = np.zeros(n)
    for p in parts:
        out[: len(p)] += p
    return out


def add(buf, snd, t, gain):
    i = int(t * SR)
    if i >= len(buf):
        return
    j = min(len(buf), i + len(snd))
    buf[i:j] += snd[: j - i] * gain


def build_music(total, fight_end):
    rng = np.random.default_rng(7)
    buf = np.zeros(int(total * SR))
    bpm = 132
    beat = 60 / bpm
    kick = tone(150, 40, 0.35, 0.12)
    hat = noise(0.06, 0.015, rng) * 0.6
    hat = np.diff(np.concatenate([[0], hat]))  # crude highpass
    snare = mix(noise(0.2, 0.05, rng) * 0.7, tone(220, 160, 0.2, 0.05) * 0.4)
    prog = [110.0, 87.31, 130.81, 98.0]  # A2 F2 C3 G2
    t = 0.0
    b = 0
    while t < fight_end:
        add(buf, kick, t, 0.55)
        add(buf, hat, t + beat / 2, 0.25)
        if b % 2 == 1:
            add(buf, snare, t, 0.30)
        root = prog[(b // 4) % 4]
        for k in range(2):
            nt = t + k * beat / 2
            dur = beat / 2 * 0.9
            n = int(dur * SR)
            tt = np.arange(n) / SR
            f = root * (2 if k == 1 else 1)
            s = (np.sin(2 * np.pi * f * tt) + 0.4 * np.sin(4 * np.pi * f * tt)
                 + 0.2 * np.sin(6 * np.pi * f * tt)) * env(n, 0.005, 0.12)
            add(buf, s, nt, 0.22)
        t += beat
        b += 1
    return buf


def build_audio(events, n_frames, total, fight_end, path):
    rng = np.random.default_rng(1)
    sfx = np.zeros(int(total * SR))
    last_hit = -1.0
    last_wall = -1.0
    for e in events:
        t = e[0] / FPS
        kind = e[1]
        if kind == "hit" and t - last_hit > 0.035:
            f0 = rng.uniform(420, 700)
            s = mix(tone(f0, f0 * 0.5, 0.14, 0.05), noise(0.03, 0.006, rng) * 0.5)
            add(sfx, s, t, 0.35)
            last_hit = t
        elif kind == "crit":
            s = mix(tone(260, 70, 0.3, 0.09, "square") * 0.8, noise(0.12, 0.03, rng) * 0.6)
            add(sfx, s, t, 0.5)
            last_hit = t
        elif kind == "kill":
            s = mix(tone(180, 35, 0.8, 0.25), noise(0.7, 0.18, rng, lowpass=0.08) * 0.9)
            add(sfx, s, t, 0.75)
        elif kind == "wall" and t - last_wall > 0.08:
            add(sfx, tone(900, 700, 0.05, 0.012), t, 0.06)
            last_wall = t
    # "FIGHT!" whoosh at the start
    add(sfx, mix(noise(0.5, 0.15, rng, lowpass=0.2) * 0.6, tone(200, 800, 0.4, 0.2) * 0.4), 0.0, 0.5)
    # victory fanfare
    for k, fr in enumerate([523.25, 659.25, 783.99, 1046.5]):
        add(sfx, tone(fr, fr, 0.5, 0.25, "square") * 0.6, fight_end + 0.15 + k * 0.11, 0.3)
    for fr in [523.25, 659.25, 783.99]:
        add(sfx, tone(fr, fr, 2.5, 0.9), fight_end + 0.6, 0.25)
    add(sfx, noise(2.5, 0.8, rng) * 0.25, fight_end + 0.6, 0.25)  # cheer-ish wash

    music = build_music(total, fight_end)
    master = music * 0.7 + sfx
    master /= max(1.0, np.abs(master).max() / 0.95)
    stereo = np.stack([master, master], axis=1)
    pcm = (stereo * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


