def pil_to_surface(img):
    img = img.convert("RGBA")
    arr = np.array(img).astype(np.float32)
    a = arr[..., 3:4] / 255.0
    bgra = np.empty_like(arr)
    bgra[..., 0] = arr[..., 2] * a[..., 0]
    bgra[..., 1] = arr[..., 1] * a[..., 0]
    bgra[..., 2] = arr[..., 0] * a[..., 0]
    bgra[..., 3] = arr[..., 3]
    data = np.ascontiguousarray(bgra.astype(np.uint8))
    h, w = data.shape[:2]
    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, w, h)
    buf = np.ndarray((h, surf.get_stride() // 4, 4), dtype=np.uint8, buffer=surf.get_data())
    buf[:, :w] = data
    surf.mark_dirty()
    return surf


def make_flag_sprites(code):
    font = ImageFont.truetype(EMOJI_FONT, 109)
    im = Image.new("RGBA", (160, 140), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((0, 0), flag_emoji(code), font=font, embedded_color=True)
    bb = im.getbbox()
    flag = im.crop(bb)
    fw, fh = flag.size
    # flag emoji has rounded corners/shading; take the middle and fill a circle
    inset = 6
    core = flag.crop((inset, inset, fw - inset, fh - inset))
    S = 4 * BALL_R
    scale = S / min(core.size)
    core = core.resize((int(core.size[0] * scale) + 1, int(core.size[1] * scale) + 1), Image.LANCZOS)
    ox = (core.size[0] - S) // 2
    oy = (core.size[1] - S) // 2
    sq = core.crop((ox, oy, ox + S, oy + S))
    mask = Image.new("L", (S * 2, S * 2), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, S * 2 - 1, S * 2 - 1), fill=255)
    mask = mask.resize((S, S), Image.LANCZOS)
    ball = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    ball.paste(sq, (0, 0), mask)
    # glossy highlight
    gloss = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    gd = ImageDraw.Draw(gloss)
    gd.ellipse((S * 0.18, S * 0.08, S * 0.62, S * 0.40), fill=(255, 255, 255, 60))
    ball = Image.alpha_composite(ball, Image.composite(gloss, Image.new("RGBA", (S, S)), mask))
    # palette for explosion particles
    px = np.array(sq.convert("RGB")).reshape(-1, 3)
    cols = [tuple(c / 255 for c in px[random.Random(i).randrange(len(px))]) for i in range(24)]
    flat = pil_to_surface(flag.resize((int(fw * 0.42), int(fh * 0.42)), Image.LANCZOS))
    return pil_to_surface(ball), flat, cols


def make_background():
    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W + 80, H + 80)
    c = cairo.Context(surf)
    g = cairo.LinearGradient(0, 0, 0, H)
    g.add_color_stop_rgb(0, 0.05, 0.04, 0.13)
    g.add_color_stop_rgb(0.5, 0.09, 0.06, 0.20)
    g.add_color_stop_rgb(1, 0.03, 0.03, 0.09)
    c.set_source(g)
    c.paint()
    c.set_source_rgba(1, 1, 1, 0.035)
    c.set_line_width(2)
    for x in range(0, W + 80, 60):
        c.move_to(x, 0); c.line_to(x, H + 80)
    for y in range(0, H + 80, 60):
        c.move_to(0, y); c.line_to(W + 80, y)
    c.stroke()
    v = cairo.RadialGradient(CX + 40, CY + 40, 300, CX + 40, CY + 40, 1300)
    v.add_color_stop_rgba(0, 0, 0, 0, 0)
    v.add_color_stop_rgba(1, 0, 0, 0, 0.7)
    c.set_source(v)
    c.paint()
    return surf


