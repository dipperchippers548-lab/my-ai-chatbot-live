def render(codes, frames, events, winner, order, out_path):
    names = [COUNTRIES.get(c, c) for c in codes]
    sprites = [make_flag_sprites(c) for c in codes]
    bg = make_background()
    n = len(codes)
    rng = random.Random(3)

    by_frame = {}
    for e in events:
        by_frame.setdefault(e[0], []).append(e)

    fight_frames = len(frames)
    end_frames = int(4.5 * FPS)
    total_frames = fight_frames + end_frames
    total = total_frames / FPS

    tmp_video = out_path + ".video.mp4"
    tmp_audio = out_path + ".wav"
    ff = subprocess.Popen([
        "ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "bgra",
        "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-",
        "-c:v", "libx264", "-preset", "medium", "-crf", "19", "-pix_fmt", "yuv420p", tmp_video,
    ], stdin=subprocess.PIPE)

    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, W, H)
    c = cairo.Context(surf)
    particles = []   # [x, y, vx, vy, life, max, r, g, b, size, gravity]
    popups = []      # [x, y, text, color, life, size]
    rings = []       # [x, y, life]
    feed = []        # [killer_idx, victim_idx, frame]
    shake = 0.0
    kill_flash = 0.0
    alive_count = n

    last = frames[-1]
    wx0, wy0 = last["balls"][winner][0], last["balls"][winner][1]

    for fi in range(total_frames):
        in_fight = fi < fight_frames
        st = frames[min(fi, fight_frames - 1)]
        t = fi / FPS

        for e in by_frame.get(fi, []) if in_fight else []:
            kind = e[1]
            if kind in ("hit", "crit"):
                _, _, att, dfd, dmg, hx, hy = e
                crit = kind == "crit"
                popups.append([hx + rng.uniform(-20, 20), hy - 20,
                               (f"CRIT -{dmg}" if crit else f"-{dmg}"),
                               (1, 0.2, 0.25) if crit else (1, 0.9, 0.2), 1.0, 58 if crit else 44])
                for _ in range(14 if crit else 7):
                    a = rng.uniform(0, 2 * math.pi); sp = rng.uniform(150, 520)
                    particles.append([hx, hy, sp * math.cos(a), sp * math.sin(a), 0.35, 0.35,
                                      1, 0.95, 0.6, rng.uniform(3, 6), 0])
                if crit:
                    shake = max(shake, 14)
            elif kind == "kill":
                _, _, att, dfd, _, kx, ky = e
                cols = sprites[dfd][2]
                for _ in range(70):
                    a = rng.uniform(0, 2 * math.pi); sp = rng.uniform(100, 900)
                    col = rng.choice(cols)
                    particles.append([kx, ky, sp * math.cos(a), sp * math.sin(a), 1.1, 1.1,
                                      *col, rng.uniform(5, 12), 600])
                rings.append([kx, ky, 0.0])
                feed.append([att, dfd, fi])
                shake = max(shake, 26)
                kill_flash = 1.0
                alive_count -= 1
                popups.append([kx, ky - 60, "ELIMINATED", (1, 1, 1), 1.3, 54])

        # ---- background + camera shake
        sx = rng.uniform(-shake, shake); sy = rng.uniform(-shake, shake)
        shake *= 0.86
        c.set_operator(cairo.OPERATOR_SOURCE)
        c.set_source_surface(bg, -40 + sx * 0.5, -40 + sy * 0.5)
        c.paint()
        c.set_operator(cairo.OPERATOR_OVER)
        c.save()
        c.translate(sx, sy)

        R = st["R"]
        sudden = st["sudden"]
        ring_rgb = (1, 0.25, 0.3) if sudden else (0.2, 0.85, 1.0)
        # arena floor
        g = cairo.RadialGradient(CX, CY, 0, CX, CY, R)
        g.add_color_stop_rgba(0, *ring_rgb, 0.10)
        g.add_color_stop_rgba(1, *ring_rgb, 0.03)
        c.arc(CX, CY, R, 0, 2 * math.pi)
        c.set_source(g)
        c.fill()
        # glowing ring
        pulse = 0.5 + 0.5 * math.sin(t * 8) if sudden else 1
        for wdt, al in ((34, 0.06), (20, 0.12), (10, 0.3), (5, 1.0)):
            c.arc(CX, CY, R, 0, 2 * math.pi)
            c.set_source_rgba(*ring_rgb, al * (0.6 + 0.4 * pulse))
            c.set_line_width(wdt)
            c.stroke()

        # ---- balls
        if in_fight:
            for i, (x, y, hp, alive, flash) in enumerate(st["balls"]):
                if not alive:
                    continue
                pop = min(1, t / 0.45 + 0) if t < 0.45 else 1
                s = ease_out_back(pop) if pop < 1 else 1
                draw_ball(c, sprites[i][0], x, y, BALL_R * s, hp, flash, codes[i])
        else:
            et = (fi - fight_frames) / FPS
            k = min(1, et / 0.8)
            k = 1 - (1 - k) ** 3
            x = wx0 + (CX - wx0) * k
            y = wy0 + (CY - wy0) * k
            r = BALL_R * (1 + 2.6 * k)
            # light rays
            c.save()
            c.translate(x, y)
            c.rotate(et * 0.6)
            for ray in range(14):
                c.rotate(2 * math.pi / 14)
                c.move_to(0, 0)
                c.line_to(900, -70)
                c.line_to(900, 70)
                c.close_path()
                c.set_source_rgba(1, 0.85, 0.3, 0.10 * k)
                c.fill()
            c.restore()
            draw_ball(c, sprites[winner][0], x, y, r, 100, 0, None, show_hp=False)
            if fi == fight_frames:
                for _ in range(160):
                    particles.append([rng.uniform(0, W), rng.uniform(-400, 0), rng.uniform(-80, 80),
                                      rng.uniform(100, 400), 4.5, 4.5,
                                      *rng.choice([(1, .3, .3), (1, .85, .2), (.3, .8, 1), (.4, 1, .5), (1, .5, 1)]),
                                      rng.uniform(6, 12), 120])

        # ---- shockwave rings
        for rg in rings:
            rg[2] += 1 / FPS
            p = rg[2] / 0.5
            if p < 1:
                c.arc(rg[0], rg[1], 30 + 220 * p, 0, 2 * math.pi)
                c.set_source_rgba(1, 1, 1, 0.8 * (1 - p))
                c.set_line_width(10 * (1 - p) + 1)
                c.stroke()
        rings[:] = [r_ for r_ in rings if r_[2] < 0.5]

        # ---- particles
        for p in particles:
            p[3] += p[10] / FPS
            p[0] += p[2] / FPS; p[1] += p[3] / FPS
            p[2] *= 0.97
            p[4] -= 1 / FPS
            a = max(0, p[4] / p[5])
            c.set_source_rgba(p[6], p[7], p[8], a)
            c.rectangle(p[0] - p[9] / 2, p[1] - p[9] / 2, p[9], p[9])
            c.fill()
        particles[:] = [p for p in particles if p[4] > 0]

        # ---- popups
        for pp in popups:
            pp[4] -= 1 / FPS * 1.4
            pp[1] -= 70 / FPS
            a = min(1, pp[4] * 2)
            text(c, pp[2], pp[0], pp[1], pp[5], pp[3], stroke=7, alpha=max(0, a))
        popups[:] = [pp for pp in popups if pp[4] > 0]
        c.restore()

        # kill flash
        if kill_flash > 0:
            c.set_source_rgba(1, 1, 1, 0.18 * kill_flash)
            c.paint()
            kill_flash = max(0, kill_flash - 0.12)

        # ---- HUD
        if in_fight:
            text(c, "WHICH COUNTRY", W / 2, 190, 92, (1, 1, 1), stroke=12)
            text(c, "WINS?", W / 2, 300, 120, (1, 0.85, 0.2), stroke=14)
            # alive pill
            pill_w = 360
            c.new_path()
            rounded(c, W / 2 - pill_w / 2, 350, pill_w, 76, 38)
            c.set_source_rgba(0, 0, 0, 0.55)
            c.fill()
            text(c, f"{alive_count} / {n} ALIVE", W / 2, 403, 46, (1, 1, 1), stroke=0)
            if sudden:
                a = 0.6 + 0.4 * math.sin(t * 10)
                text(c, "SUDDEN DEATH", W / 2, CY - R - 40, 60, (1, 0.3, 0.3), stroke=9, alpha=a)
            if t < 0.9:
                k = t / 0.9
                sc = 1.6 - 0.6 * min(1, k * 3)
                text(c, "FIGHT!", W / 2, CY + 40, 170 * sc, (1, 1, 1), stroke=16, alpha=1 - k ** 3)
            # kill feed
            recent = [f_ for f_ in feed if fi - f_[2] < FPS * 3.2][-4:]
            for row, (killer, victim, f0) in enumerate(reversed(recent)):
                age = (fi - f0) / FPS
                a = min(1, age * 6) * min(1, (3.2 - age) * 3)
                draw_feed_row(c, sprites, names, killer, victim, 1590 + row * 72, a)
        else:
            et = (fi - fight_frames) / FPS
            a = min(1, max(0, (et - 0.5) * 4))
            sc = 1 + 0.25 * max(0, 1 - (et - 0.5) * 3)
            text(c, names[winner], W / 2, 360, 140 * sc, (1, 0.85, 0.2), stroke=16, alpha=a)
            text(c, "WINS!", W / 2, 500, 130 * sc, (1, 1, 1), stroke=16, alpha=a)
            a2 = min(1, max(0, (et - 1.2) * 4))
            if len(order) >= 2:
                text(c, f"2ND  {names[order[-1]]}", W / 2, 1560, 58, (0.85, 0.88, 0.95), stroke=8, alpha=a2)
                text(c, f"3RD  {names[order[-2]]}", W / 2, 1640, 50, (0.85, 0.6, 0.35), stroke=8, alpha=a2)
            a3 = min(1, max(0, (et - 1.8) * 4))
            text(c, "COMMENT YOUR COUNTRY", W / 2, 1780, 64, (1, 1, 1), stroke=10, alpha=a3)
            text(c, "FOR THE NEXT BATTLE", W / 2, 1855, 50, (0.6, 0.9, 1), stroke=8, alpha=a3)

        surf.flush()
        ff.stdin.write(bytes(surf.get_data()))
        if fi % 300 == 0:
            print(f"  frame {fi}/{total_frames}", flush=True)

    ff.stdin.close()
    ff.wait()
    build_audio(events, total_frames, total, fight_frames / FPS, tmp_audio)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp_video, "-i", tmp_audio,
                    "-c:v", "copy", "-c:a", "aac", "-b:a", "192k", "-shortest", out_path], check=True)
    os.remove(tmp_video)
    os.remove(tmp_audio)
    return total


def rounded(c, x, y, w, h, r):
    c.arc(x + w - r, y + r, r, -math.pi / 2, 0)
    c.arc(x + w - r, y + h - r, r, 0, math.pi / 2)
    c.arc(x + r, y + h - r, r, math.pi / 2, math.pi)
    c.arc(x + r, y + r, r, math.pi, 3 * math.pi / 2)
    c.close_path()


def draw_ball(c, sprite, x, y, r, hp, flash, code, show_hp=True):
    if r < 2:
        return
    S = sprite.get_width()
    # shadow
    c.arc(x + 6, y + 10, r, 0, 2 * math.pi)
    c.set_source_rgba(0, 0, 0, 0.35)
    c.fill()
    c.save()
    c.translate(x - r, y - r)
    c.scale(2 * r / S, 2 * r / S)
    c.set_source_surface(sprite, 0, 0)
    c.get_source().set_filter(cairo.FILTER_GOOD)
    c.paint()
    c.restore()
    if flash > 0:
        c.arc(x, y, r, 0, 2 * math.pi)
        c.set_source_rgba(1, 1, 1, 0.7 * flash)
        c.fill()
    c.arc(x, y, r, 0, 2 * math.pi)
    c.set_source_rgba(1, 1, 1, 0.95)
    c.set_line_width(4 if show_hp else 10)
    c.stroke()
    if show_hp:
        # HP arc
        c.arc(x, y, r + 9, 0, 2 * math.pi)
        c.set_source_rgba(0, 0, 0, 0.5)
        c.set_line_width(7)
        c.stroke()
        c.arc(x, y, r + 9, -math.pi / 2, -math.pi / 2 + 2 * math.pi * max(0, hp) / 100)
        c.set_source_rgb(*hp_color(hp))
        c.set_line_width(7)
        c.stroke()
        if code:
            text(c, code, x, y + r + 40, 28, (1, 1, 1), stroke=6)


def draw_feed_row(c, sprites, names, killer, victim, y, a):
    if a <= 0:
        return
    s1 = sprites[killer][1]
    s2 = sprites[victim][1]
    c.select_font_face(FONT, cairo.FONT_SLANT_NORMAL, cairo.FONT_WEIGHT_BOLD)
    c.set_font_size(36)
    w1 = c.text_extents(names[killer]).x_advance
    w2 = c.text_extents(names[victim]).x_advance
    total = s1.get_width() + 12 + w1 + 70 + s2.get_width() + 12 + w2
    x = W / 2 - total / 2
    c.new_path()
    rounded(c, x - 24, y - 28, total + 48, 60, 30)
    c.set_source_rgba(0, 0, 0, 0.55 * a)
    c.fill()
    c.set_source_surface(s1, x, y - s1.get_height() / 2)
    c.paint_with_alpha(a)
    x += s1.get_width() + 12
    x += text(c, names[killer], x, y + 13, 36, (0.5, 1, 0.6), stroke=0, align="left", alpha=a)
    text(c, "KO", x + 35, y + 13, 32, (1, 0.4, 0.4), stroke=0, alpha=a)
    x += 70
    c.set_source_surface(s2, x, y - s2.get_height() / 2)
    c.paint_with_alpha(a * 0.8)
    x += s2.get_width() + 12
    text(c, names[victim], x, y + 13, 36, (0.75, 0.75, 0.8), stroke=0, align="left", alpha=a)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--countries", help="comma-separated ISO codes, e.g. US,BR,JP")
    ap.add_argument("--count", type=int, default=16)
    ap.add_argument("--seed", type=int)
    ap.add_argument("--winner", help="ISO code that must win (searches seeds)")
    ap.add_argument("--min-len", type=float, default=18, help="min fight seconds")
    ap.add_argument("--max-len", type=float, default=30, help="max fight seconds")
    ap.add_argument("--out", default="out/battle.mp4")
    args = ap.parse_args()

    base_seed = args.seed if args.seed is not None else random.randrange(1_000_000)
    if args.countries:
        codes = [c.strip().upper() for c in args.countries.split(",") if c.strip()]
    else:
        codes = random.Random(base_seed).sample(sorted(COUNTRIES), args.count)
    if args.winner and args.winner.upper() not in codes:
        codes[-1] = args.winner.upper()
    random.Random(base_seed).shuffle(codes)

    # find a seed giving a good-length fight (and the requested winner)
    for attempt in range(3000):
        seed = base_seed + attempt
        frames, events, winner, order = simulate(codes, seed)
        dur = len(frames) / FPS
        ok = args.min_len <= dur <= args.max_len
        if args.winner:
            ok = ok and codes[winner] == args.winner.upper()
        if ok:
            break
    else:
        sys.exit("could not find a matching seed; loosen --min-len/--max-len")

    print(f"seed {seed}: {COUNTRIES.get(codes[winner], codes[winner])} wins after {dur:.1f}s "
          f"({sum(1 for e in events if e[1] == 'kill')} KOs)")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    total = render(codes, frames, events, winner, order, args.out)
    print(f"wrote {args.out} ({total:.1f}s)")


if __name__ == "__main__":
    main()
